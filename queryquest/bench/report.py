"""Turn recorded measurements into a Markdown report.

Every number in docs/BENCHMARKS.md is read out of qq_meta at generation
time. Nothing is typed by hand, which means the document cannot drift
from what the harness actually measured -- and if someone re-runs the
suite on different hardware, the report changes with it instead of
quietly lying.
"""

from __future__ import annotations

import platform
from datetime import datetime, timezone
from pathlib import Path

import psycopg
from psycopg.rows import dict_row

from ..config import META_SCHEMA, OPTIMIZED_SCHEMA, REPO_ROOT
from ..db import server_version, table_counts


def _table(headers: list[str], rows: list[list[str]]) -> str:
    line = "| " + " | ".join(headers) + " |"
    rule = "|" + "|".join("---:" if i else ":---" for i in range(len(headers))) + "|"
    body = "\n".join("| " + " | ".join(r) + " |" for r in rows)
    return "\n".join([line, rule, body])


def _speedup(baseline: float, optimized: float) -> str:
    if not optimized:
        return "n/a"
    return f"{baseline / optimized:.1f}x"


def fetch_run(conn: psycopg.Connection, run_id: str | None = None) -> tuple[str, list[dict]]:
    with conn.cursor(row_factory=dict_row) as cur:
        if run_id is None:
            cur.execute(
                f"SELECT run_id FROM {META_SCHEMA}.query_benchmarks "
                f"ORDER BY recorded_at DESC LIMIT 1"
            )
            row = cur.fetchone()
            if row is None:
                raise RuntimeError("no benchmark runs recorded yet")
            run_id = row["run_id"]

        cur.execute(
            f"""
            SELECT query_name, variant, repetitions, p50_ms, p95_ms, p99_ms,
                   mean_ms, min_ms, max_ms, rows_returned, shared_hit, shared_read
            FROM {META_SCHEMA}.query_benchmarks
            WHERE run_id = %s
            ORDER BY query_name, variant
            """,
            (run_id,),
        )
        return run_id, cur.fetchall()


def fetch_cache_runs(conn: psycopg.Connection, limit: int = 4) -> list[dict]:
    with conn.cursor(row_factory=dict_row) as cur:
        cur.execute(
            f"""
            SELECT workload, concurrency, duration_s, queries_total, queries_per_min,
                   hits, misses, hit_ratio, p50_ms, p95_ms, p99_ms, recorded_at
            FROM {META_SCHEMA}.cache_stats
            ORDER BY recorded_at DESC
            LIMIT %s
            """,
            (limit,),
        )
        return cur.fetchall()


def fetch_etl_batches(conn: psycopg.Connection, limit: int = 20) -> list[dict]:
    with conn.cursor(row_factory=dict_row) as cur:
        cur.execute(
            f"""
            SELECT target_table, state, rows_read, rows_duplicate, rows_rejected,
                   rows_inserted, rows_updated, rows_unchanged, duration_ms
            FROM {META_SCHEMA}.etl_batches
            ORDER BY batch_id DESC
            LIMIT %s
            """,
            (limit,),
        )
        return cur.fetchall()


def build_report(conn: psycopg.Connection, run_id: str | None = None) -> str:
    run_id, rows = fetch_run(conn, run_id)

    by_query: dict[str, dict[str, dict]] = {}
    for r in rows:
        by_query.setdefault(r["query_name"], {})[r["variant"]] = r

    counts = table_counts(conn, OPTIMIZED_SCHEMA)
    total_rows = sum(counts.values())
    pg = server_version(conn)

    out: list[str] = []
    out.append("# Benchmarks\n")
    out.append(
        "> Generated by `python -m queryquest.cli report`. Every figure is read "
        f"from `{META_SCHEMA}.query_benchmarks` and `{META_SCHEMA}.cache_stats` -- "
        "the tables the harness writes to. Re-run the suite and this file changes "
        "with it.\n"
    )

    out.append("## Environment\n")
    out.append(
        _table(
            ["Property", "Value"],
            [
                ["Run id", f"`{run_id}`"],
                ["Generated", datetime.now(timezone.utc).strftime("%Y-%m-%d %H:%M UTC")],
                ["PostgreSQL", pg],
                ["Python", platform.python_version()],
                ["Platform", f"{platform.system()} {platform.release()} ({platform.machine()})"],
                ["Rows in `qq` (12 tables)", f"{total_rows:,}"],
            ],
        )
    )
    out.append("")

    out.append("## Row counts\n")
    out.append(
        _table(
            ["Table", "Rows"],
            [[f"`{t}`", f"{n:,}"] for t, n in counts.items()]
            + [["**total**", f"**{total_rows:,}**"]],
        )
    )
    out.append("")

    out.append("## Query latency: baseline vs optimized\n")
    out.append(
        "`baseline` is the `qq_baseline` schema -- identical rows, primary keys "
        "only, no partitioning, no materialized views. `optimized` is `qq`. "
        "Same box, same parameter values, warm-up repetitions discarded.\n"
    )

    rows_out: list[list[str]] = []
    p95_base_total = p95_opt_total = 0.0
    for name in sorted(by_query):
        b = by_query[name].get("baseline")
        o = by_query[name].get("optimized")
        if not b or not o:
            continue
        p95_base_total += float(b["p95_ms"])
        p95_opt_total += float(o["p95_ms"])
        rows_out.append(
            [
                f"`{name}`",
                f"{float(b['p50_ms']):,.1f}",
                f"{float(b['p95_ms']):,.1f}",
                f"{float(o['p50_ms']):,.1f}",
                f"{float(o['p95_ms']):,.1f}",
                _speedup(float(b["p95_ms"]), float(o["p95_ms"])),
            ]
        )

    out.append(
        _table(
            ["Query", "base p50 (ms)", "base p95 (ms)", "opt p50 (ms)", "opt p95 (ms)", "p95 speed-up"],
            rows_out,
        )
    )
    out.append("")

    if p95_opt_total:
        out.append(
            f"**Suite total p95: {p95_base_total:,.1f} ms -> {p95_opt_total:,.1f} ms "
            f"({p95_base_total / p95_opt_total:.1f}x).**\n"
        )

    out.append("## Buffer accounting\n")
    out.append(
        "`shared_read` is pages fetched from disk, `shared_hit` is pages already "
        "in the buffer cache, both taken from `EXPLAIN (ANALYZE, BUFFERS)`. This "
        "is the part that explains *why* the timings moved: an index that turns "
        "reads into hits is doing real work, not shuffling time around.\n"
    )
    buf_rows = []
    for name in sorted(by_query):
        b = by_query[name].get("baseline")
        o = by_query[name].get("optimized")
        if not b or not o:
            continue
        buf_rows.append(
            [
                f"`{name}`",
                f"{int(b['shared_hit']):,}",
                f"{int(b['shared_read']):,}",
                f"{int(o['shared_hit']):,}",
                f"{int(o['shared_read']):,}",
            ]
        )
    out.append(
        _table(
            ["Query", "base hit", "base read", "opt hit", "opt read"], buf_rows
        )
    )
    out.append("")

    cache_runs = fetch_cache_runs(conn)
    if cache_runs:
        out.append("## Cached read throughput\n")
        out.append(
            "Closed-loop load test over the storefront read mix, 80/20 key skew. "
            "The uncached row runs the identical code path with the cache "
            "disabled.\n"
        )
        out.append(
            _table(
                ["Workload", "Threads", "Queries", "Queries/min", "Hit ratio", "p50 (ms)", "p95 (ms)"],
                [
                    [
                        f"`{r['workload']}`",
                        str(r["concurrency"]),
                        f"{r['queries_total']:,}",
                        f"{float(r['queries_per_min']):,.0f}",
                        f"{float(r['hit_ratio']):.1%}",
                        f"{float(r['p50_ms']):,.2f}",
                        f"{float(r['p95_ms']):,.2f}",
                    ]
                    for r in cache_runs
                ],
            )
        )
        out.append("")

    batches = fetch_etl_batches(conn)
    if batches:
        out.append("## Most recent ETL batches\n")
        out.append(
            _table(
                ["Table", "State", "Read", "Dup", "Rejected", "Inserted", "Updated", "Unchanged", "ms"],
                [
                    [
                        f"`{b['target_table']}`",
                        b["state"],
                        f"{b['rows_read']:,}",
                        f"{b['rows_duplicate']:,}",
                        f"{b['rows_rejected']:,}",
                        f"{b['rows_inserted']:,}",
                        f"{b['rows_updated']:,}",
                        f"{b['rows_unchanged']:,}",
                        f"{b['duration_ms'] or 0:,}",
                    ]
                    for b in batches
                ],
            )
        )
        out.append("")
        out.append(
            "A second run of the same feeds reports `skipped_duplicate`, or -- "
            "with `--force` -- zero inserts and zero updates. That is the "
            "idempotency claim, measured rather than asserted.\n"
        )

    return "\n".join(out)


def write_report(conn: psycopg.Connection, run_id: str | None = None, path: Path | None = None) -> Path:
    path = path or (REPO_ROOT / "docs" / "BENCHMARKS.md")
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text(build_report(conn, run_id), encoding="utf-8")
    return path
